package com.pilot.agent.agent

/**
 * 意图门：判断一句话是「操作指令」还是「闲聊/提问」。
 *
 * ## 为什么必须有
 * 语音输入不区分意图就送进 agent loop，后果很严重：用户说「你是谁呀」，
 * agent 会当成任务去点屏幕上的第一个可点元素。实测真机上一句话触发了 3 次乱点。
 *
 * 所以凡是没过这道门的句子，一律不执行任何设备操作。
 *
 * ## 判据
 * 不看问号看动词。「今天几号」是提问但不该乱点；「帮我看看几点了」有动词但也不该乱点。
 * 所以先认**操作动词**，再排除纯疑问句：
 * - 有操作动词 + 不是纯问句 → 任务
 * - 没有操作动词 → 交流（不执行）
 */
object IntentGate {

    /** 三类意图。原来只有「任务 / 非任务」，查询类被误判成闲聊扔给了端侧小模型 */
    enum class Kind { TASK, QUERY, CHAT }

    /**
     * 「免打扰」类话术：让助手先歇着，别再听着。
     *
     * ★ 命中后要退出聆听状态，直到用户再喊唤醒词或长按输入框。
     *   否则用户说完「我先忙一会」就安静了，但助手还在活跃期内听着，
     *   后面的话全被当成指令执行（用户明确要求这个行为）。
     *
     * 判据是**短语组合**而不是单个词：
     * "别打扰我" / "你先歇着" / "休息一会" / "我先忙一会" / "别跟着我"…
     * 单看"休息"会误伤"我休息好了继续播放音乐"这类真任务。
     */
    private val DND_PHRASES = listOf(
        "别打扰我", "不要打扰我", "别来打扰", "别烦我", "别跟着我",
        "你先歇着", "你先休息", "你先歇歇", "你先待着", "你先安静",
        "休息一会", "休息会儿", "歇一会", "歇会儿",
        "我先忙一会", "我先忙会儿", "我要忙一会", "我要忙会儿",
        "先别说话", "先别跟着", "暂时别说话", "暂时不用跟着",
        "我自己来", "不用管我", "别管我", "先不聊了",
    )

    /**
     * 判断是不是"让助手歇着"的话。
     *
     * @param text 用户说的话
     * @return true = 该退出聆听状态
     */
    fun isDoNotDisturb(text: String): Boolean {
        val t = text.trim().replace("，", "").replace("。", "").replace("、", "")
        if (t.isEmpty()) return false
        // 有动词+设备对象的话更像任务（"我先忙完工作你放音乐"）→ 不算免打扰
        if (TASK_VERBS.any { t.contains(it) }) return false
        return DND_PHRASES.any { t.contains(it) }
    }

    /** 查询类：要的是信息，不是动作。走 QueryEngine，不碰屏幕 */
    private val QUERY_HINTS = listOf(
        "查一下", "查查", "查询", "搜一下", "看看", "多少", "几号", "几点",
        "怎么样", "怎么走", "是什么", "是谁", "为什么", "行情", "股价", "指数",
        "涨了", "跌了", "天气", "新闻", "快递", "汇率", "油价", "限行",
        "财经", "娱乐", "明星", "影视", "ai动态", "大模型", "人工智能",
        "科技动态", "最新消息", "最新动态", "头条", "热点", "读通知", "最新通知",
        "通知摘要", "有什么通知", "读一下消息通知",
    )

    /** 能落到具体设备动作上的动词 */
    private val TASK_VERBS = listOf(
        "打开", "启动", "运行", "关闭", "关掉", "退出",
        "点击", "点一下", "点开", "按一下", "长按", "选择",
        "输入", "填", "搜索", "搜一下", "查找",
        "返回", "回到", "退出到", "滑", "滚动", "翻页",
        "设置", "调", "调成", "开启", "关掉开关", "静音",
        "发消息", "发送", "拨号", "打电话", "分享",
        "截图", "截屏", "录屏",
        "安装", "卸载", "删除",
        // 系统导航类：用户常说「回桌面」，不带"打开"这种动词
        "桌面", "主页", "通知栏", "最近任务", "多任务",
        // 系统能力直调类：「声音大一点」「亮度小一点」没有"打开/点击"，但有明确的可执行意图
        "音量", "声音", "亮度", "屏幕亮", "大声", "小声",
        "调大", "调小", "调高", "调低", "静音", "免打扰",
        // 媒体类：「播放晴天」既没有动词也不含设备名词，最容易漏
        "播放", "放首", "放一首", "来首", "来一首", "听歌", "放歌",
        "暂停", "继续播放", "下一首", "上一首", "切歌",
        // 沙箱终端类（HANDOFF 坑 #13：每加一类执行能力必须同步这里）
        "终端", "沙箱", "命令", "跑个", "跑一下", "执行命",
        // 导航类：「导航去西湖」「带我去机场」「停止导航」「还有多远」
        "导航", "带我去", "路线", "还有多远", "到哪了",
        // 本地提醒、日程、待办
        "提醒我", "记得提醒", "我的提醒", "取消提醒", "日历", "日程", "待办", "加到日历",
    )

    /**
     * 自我介绍/身份类问题。
     *
     * ★ 为什么要单独列（老板 11-10 反馈：「你是谁这样的问题不要走规则，
     *   模型交给模型回答」）：
     *   原来靠 QUERY_HINTS 判，而 QUERY_HINTS 里有「是谁」——
     *   「你是谁」包含「是谁」，于是被误判成查询类。
     *   更糟的是查询类会去找数据源，没有数据源才 fallback 到模型，
     *   等于绕了一圈才到模型，规则在这里纯属添乱。
     *
     *   判据刻意收窄到「你 + 身份/能力词」这类**明确在问模型自己**的说法，
     *   避免误伤「谁是谁的联系人」这种真查询。
     */
    private val SELF_ASK = listOf(
        "你是谁", "你叫什么", "你叫啥", "你叫什麼", "你是什么",
        "你能做什么", "你会做什么", "你能干什么", "你会干什么",
        "介绍一下你自己", "自我介绍", "你是什么助手", "你是什么ai",
    )

    /** 这些表达明确要外部实时资讯；“搜一下新闻”不能被误判成操作屏幕的搜索指令。 */
    private val LIVE_INFO_HINTS = listOf(
        "新闻", "资讯", "消息", "动态", "最新", "财经", "娱乐", "明星", "影视",
        "人工智能", "大模型", "科技", "头条", "热点",
    )
    private val WEB_SEARCH_HINTS = listOf(
        "网页", "网上搜", "上网搜", "上网查", "网上查", "帮我搜", "搜一下", "搜索一下",
        "搜索", "查资料", "查官网", "网页搜索", "读网页", "阅读网页", "总结网页", "这篇文章",
    )
    private val DEVICE_ACTION_HINTS = listOf(
        "打开", "启动", "关闭", "关掉", "点击", "输入", "返回", "回到", "发消息",
        "拨号", "打电话", "分享", "截图", "截屏", "安装", "卸载", "删除", "设置",
    )

    /** 纯交流的开头，命中就不当成任务 */
    private val CHAT_PREFIX = listOf(
        "你是谁", "你叫", "你能做什么", "你会", "你好", "在吗", "在不在",
        "为什么", "怎么", "什么是", "介绍一下", "讲个", "说个",
        "今天", "明天", "现在几点", "天气",
    )

    fun isTask(text: String): Boolean = classify(text) == Kind.TASK

    /**
     * 三分类。
     *
     * 顺序有讲究：**先判任务再判查询**。「打开设置看看有什么」是任务（有操作动词），
     * 「查一下上证指数」是查询（没有操作动词）。反过来判会把前者误归查询。
     */
    fun classify(text: String): Kind {
        val t = text.trim()
        if (t.isEmpty()) return Kind.CHAT

        val startsWithChat = CHAT_PREFIX.any { t.startsWith(it) }
        val hasVerb = TASK_VERBS.any { t.contains(it) }
        val hasQuery = QUERY_HINTS.any { t.contains(it) }
        // 裸 shell 命令（"df -h"、"cat /etc/alpine-release"）没有中文动词，
        // 但首 token 命中沙箱工具白名单就是明确的任务意图
        val rawShell = HeuristicPlanner.looksLikeRawShellCommand(t)
        // 在问模型自己 → 一定交给模型回答，不查数据源
        val selfAsk = SELF_ASK.any { t.contains(it) }

        // 在问自己 → 交流（模型回答）。放最前面，避免「是谁」这种
        // 泛化查询词把它误判成数据查询。
        if (selfAsk) return Kind.CHAT
        if (LIVE_INFO_HINTS.any(t::contains) && DEVICE_ACTION_HINTS.none(t::contains)) return Kind.QUERY
        if (t.contains("https://", ignoreCase = true) && listOf("网页", "链接", "文章", "总结", "阅读", "读一下", "浏览").any(t::contains)) return Kind.QUERY
        if (WEB_SEARCH_HINTS.any(t::contains) && DEVICE_ACTION_HINTS.none(t::contains)) return Kind.QUERY
        // 有操作动词 → 任务（哪怕同时有"查"，比如"打开XX查一下"）
        if (hasVerb || rawShell) return Kind.TASK
        // 纯交流开头且没有查询词 → 闲聊
        if (startsWithChat && !hasQuery) return Kind.CHAT
        // 有查询词 → 查询
        if (hasQuery) return Kind.QUERY
        return Kind.CHAT
    }

    /** 给用户看的解释 */
    fun reason(text: String): String = when {
        text.isBlank() -> "空输入"
        classify(text) == Kind.TASK -> "操作指令"
        classify(text) == Kind.QUERY -> "信息查询"
        else -> "看起来是交流而不是操作指令"
    }
}
